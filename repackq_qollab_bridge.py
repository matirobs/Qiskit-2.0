def run_qaoa(
    horizon_cycles: int,
    pack_size_k: int,
    objective_mode: str,
    shots: int,
    reps: int,
    optimizer_mode: str,
    max_evaluations: int,
    backend: Any,
) -> str:
    """Direct Python entry point; the Qollab browser uses split async methods."""

    return _json_result(_api().run_live_qaoa(
        horizon_cycles=int(horizon_cycles),
        pack_size_k=int(pack_size_k),
        objective_mode=str(objective_mode),
        shots=int(shots),
        reps=int(reps),
        optimizer_mode=str(optimizer_mode),
        max_evaluations=int(max_evaluations),
        backend=backend,
    ))


def prepare_qaoa_circuit(
    horizon_cycles: int,
    pack_size_k: int,
    objective_mode: str,
    shots: int,
    reps: int,
    optimizer_mode: str,
    max_evaluations: int,
    backend: Any,
) -> Any:
    """Build, optimize, and target-transpile locally; return a circuit proxy."""

    return _api().prepare_live_qaoa_circuit(
        backend=backend,
        horizon_cycles=int(horizon_cycles),
        pack_size_k=int(pack_size_k),
        objective_mode=str(objective_mode),
        shots=int(shots),
        reps=int(reps),
        optimizer_mode=str(optimizer_mode),
        max_evaluations=int(max_evaluations),
    )


def submit_qaoa_circuit(circuit: Any, backend: Any, shots: int) -> str:
    """Submit one measured circuit through Qollab's promising Python bridge."""

    run = getattr(backend, "run", None)
    if not callable(run):
        raise TypeError("selected backend must provide run(circuit, shots=...)")
    job = run(circuit, shots=int(shots))
    result_method = getattr(job, "result", None)
    if not callable(result_method):
        raise TypeError("selected backend run() did not return a Qiskit job")
    backend_result = result_method()
    get_counts = getattr(backend_result, "get_counts", None)
    if not callable(get_counts):
        raise TypeError("selected backend job result did not provide get_counts()")
    try:
        counts = get_counts(circuit)
    except TypeError:
        counts = get_counts()
    if not hasattr(counts, "items"):
        raise TypeError("selected backend returned counts in an unsupported format")
    normalized = {str(key): int(value) for key, value in counts.items()}
    return _json_result({"counts": normalized})


def complete_qaoa_circuit(
    circuit_name: str,
    counts_json: str,
    backend_name: str,
    backend_sampling_ms: float,
) -> str:
    """Convert bridge-submitted backend counts into QAOA diagnostics."""

    counts = json.loads(str(counts_json))
    if not isinstance(counts, dict):
        raise ValueError("Qollab backend returned counts in an unsupported format")
    normalized = {str(key): int(value) for key, value in counts.items()}
    return _json_result(_api().complete_live_qaoa_circuit(
        str(circuit_name),
        normalized,
        str(backend_name),
        float(backend_sampling_ms),
    ))


def discard_qaoa_circuit(circuit_name: str) -> str:
    """Release cached local preparation data after a backend error."""

    return _json_result({
        "discarded": bool(_api().discard_live_qaoa_circuit(str(circuit_name)))
    })


