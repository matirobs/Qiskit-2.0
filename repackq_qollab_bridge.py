"""Positional Python API exposed to Qollab's JavaScript runtime.

Qollab imports this module by its dotted module name from the HTML/JS project.
Each function has a positional signature so the JavaScript/Python boundary does
not depend on translating JavaScript option objects into Python keyword args.
The browser adapter prepares and analyzes QAOA in Python. It invokes the
selected backend submission through Qollab's ``callPromising`` bridge so
provider network calls can use the host's asynchronous Python integration.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

_UI_API: Any | None = None


def _ensure_project_package_path() -> None:
    candidates: list[Path] = []
    module_path = globals().get("__file__")
    if module_path:
        candidates.append(Path(module_path).resolve().parent)
    candidates.append(Path.cwd().resolve())
    candidates.extend(Path(item).resolve() for item in sys.path if item)

    visited: set[Path] = set()
    for candidate in candidates:
        for root in (candidate, *candidate.parents):
            if root in visited:
                continue
            visited.add(root)
            if (root / "repackq").is_dir():
                if str(root) not in sys.path:
                    sys.path.insert(0, str(root))
                return


def _api() -> Any:
    # Import the package API directly instead of importing the project's
    # ``main.py`` entrypoint. Qollab owns a JavaScript ``main.js`` entrypoint,
    # and importing a same-named Python module can be host-loader dependent.
    # Qollab's Python runtime also restricts filesystem reads, so replace the
    # UI's file-backed synthetic fixture loader with the in-memory module
    # generated by the release packager.
    global _UI_API
    if _UI_API is not None:
        return _UI_API

    _ensure_project_package_path()
    from repackq import ui
    from repackq.data.serialization import trajectories_from_dict
    from repackq_qollab_fixture import FIXTURE_JSON

    payload = json.loads(FIXTURE_JSON)
    if payload.get("data_classification") != "synthetic-fixture":
        raise ValueError("Qollab bridge fixture is not labeled synthetic-fixture")
    trajectories = trajectories_from_dict(payload)

    def load_embedded_fixture() -> tuple[dict[str, Any], list[Any]]:
        return payload, trajectories

    ui._load_fixture = load_embedded_fixture
    _UI_API = ui
    return _UI_API


def _indices_to_list(indices: Any) -> list[int]:
    converter = getattr(indices, "to_py", None)
    if callable(converter):
        indices = converter()
    return list(indices)


def _json_result(value: Any) -> str:
    """Serialize API payloads to avoid nested Python-proxy conversion in JS."""

    return json.dumps(value, allow_nan=False, separators=(",", ":"))


def get_capabilities() -> str:
    """Report whether the Qollab Python runtime can run the local QAOA engine."""

    try:
        from qiskit.quantum_info import Statevector
        _api()
    except Exception as exc:
        return _json_result({
            "available": False,
            "interactive": False,
            "bridge": "qollab-python-callpromising-v1",
            "qiskit_available": False,
            "statevector_available": False,
            "message": f"Qollab Python dependencies or the RePack-Q API are unavailable: {type(exc).__name__}: {exc}",
        })
    return _json_result({
        "available": True,
        "interactive": True,
        "bridge": "qollab-python-callpromising-v1",
        "qiskit_available": True,
        "statevector_available": Statevector is not None,
        "message": "Qollab JavaScript-to-Python bridge is ready.",
    })


def get_demo_state(horizon_cycles: int = 200, pack_size_k: int = 4) -> str:
    return _json_result(_api().get_demo_state(
        horizon_cycles=int(horizon_cycles),
        pack_size_k=int(pack_size_k),
    ))


